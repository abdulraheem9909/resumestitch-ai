// Hand-edit one tailored bullet — direct Mongo write, no graph interaction.
router.patch('/:id/bullets/:bulletId', async (req, res) => {
  const { id, bulletId } = req.params;
  if (!mongoose.isValidObjectId(id)) {
    return res.status(400).json({ error: 'Invalid application id.' });
  }

  const { text, rejected } = req.body;
  const hasText = text !== undefined;
  const hasRejected = rejected !== undefined;
  if (!hasText && !hasRejected) {
    return res.status(400).json({ error: 'text or rejected is required.' });
  }
  if (hasText && (typeof text !== 'string' || !text.trim())) {
    return res.status(400).json({ error: 'text is required.' });
  }
  if (hasRejected && typeof rejected !== 'boolean') {
    return res.status(400).json({ error: 'rejected must be a boolean.' });
  }

  try {
    const application = await Application.findOne({ _id: id, userId: req.user.id });
    if (!application) {
      return res.status(404).json({ error: 'Application not found.' });
    }

    const bullet = application.tailoredBullets.find((b) => b.bulletId === bulletId);
    if (!bullet) {
      return res.status(404).json({ error: 'Tailored bullet not found.' });
    }

    if (hasText) {
      bullet.humanEditedText = text;
      bullet.finalText = text;
      bullet.editSource = 'human';
    }
    // Human override of node 5's keep/reject call — independent of text edits,
    // so it can re-include a bullet the model judged out of context (its text
    // is already the verbatim source, per tailorContent.js, so no fabrication
    // risk) or exclude one the model kept. Tagging it rejectionSource: 'human'
    // (as opposed to node 5's own default 'ai') is what lets this decision
    // survive a later retry instead of being silently overridden — see
    // mergeHumanEditedBullets/ensureRequiredBulletIncluded/
    // ensureEveryEmployerRepresented in jobAgentGraph.js.
    if (hasRejected) {
      bullet.rejected = rejected;
      bullet.rejectionSource = 'human';
    }
    await application.save();

    const activeTexts = application.tailoredBullets
      .filter((b) => !b.rejected)
      .map((b) => b.finalText);
    const resume = await MasterResume.findOne({ _id: application.masterResumeId, userId: req.user.id }).select('skills projects');
    const effectiveSkills = application.tailoredSkills ?? resume?.skills ?? [];
    const sourceTexts = [
      ...activeTexts,
      application.tailoredSummary?.finalText,
      ...(resume?.projects || []).map((project) => project.description),
    ];
    const { aliases: bulletSkillAliases, matchers: bulletSkillMatchers } = await getSkillDictionaryForUser(req.user.id);
    const { verifiedSkills, skillMatchTypes } = computeVerifiedSkills(effectiveSkills, sourceTexts, bulletSkillMatchers, bulletSkillAliases);

    return res.json({ application, verifiedSkills, skillMatchTypes });
  } catch (err) {
    console.error(err);
    return res.status(500).json({ error: 'Failed to update tailored bullet.' });
  }
});

