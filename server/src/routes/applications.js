// A real job posting is a few KB at most. This exists to fail fast with a
// clear message instead of letting an absurdly large paste reach the JD-
// keyword-extraction LLM call, where it can blow past the provider's
// per-minute token limit and throw from deep inside the graph.
const MAX_JD_LENGTH = 20000;

// Section 3 — create + start.
router.post('/', async (req, res) => {
  const { masterResumeId, jdText, companyName, jobTitle, referenceUrl, coverLetterRequested } = req.body;

  if (!mongoose.isValidObjectId(masterResumeId)) {
    return res.status(400).json({ error: 'Invalid masterResumeId.' });
  }
  if (typeof jdText !== 'string' || !jdText.trim()) {
    return res.status(400).json({ error: 'jdText is required.' });
  }
  if (jdText.length > MAX_JD_LENGTH) {
    return res.status(400).json({ error: `jdText is too long (max ${MAX_JD_LENGTH} characters).` });
  }
  if (typeof companyName !== 'string' || !companyName.trim()) {
    return res.status(400).json({ error: 'companyName is required.' });
  }
  if (typeof jobTitle !== 'string' || !jobTitle.trim()) {
    return res.status(400).json({ error: 'jobTitle is required.' });
  }

  try {
    const normalizedJdText = jdText.trim().replace(/\s+/g, ' ');
    const jdTextHash = createHash('sha256').update(normalizedJdText).digest('hex');

    const existing = await Application.findOne({ masterResumeId, jdTextHash, userId: req.user.id });
    if (existing) {
      return res.json({ application: existing, deduped: true });
    }

    const resume = await MasterResume.findOne({ _id: masterResumeId, status: 'active', userId: req.user.id });
    if (!resume) {
      return res.status(404).json({ error: 'Resume not found.' });
    }

    const bullets = await ResumeBullet.find({ masterResumeId }).sort({ order: 1 });
    if (bullets.length === 0) {
      return res.status(400).json({ error: 'Selected resume has no bullets.' });
    }

    const { aliases: skillAliases } = await getSkillDictionaryForUser(req.user.id);
    const resumeCanonicalSkills = normalizeSkills(bullets.flatMap((bullet) => bullet.skills), skillAliases);
    const resumeBulletsForGraph = buildResumeBulletsForGraph(bullets);
    const projectCanonicalSkills = normalizeSkills(
      (resume.projects || []).flatMap((project) => project.canonicalSkills || []),
      skillAliases
    );

    let application;
    try {
      application = await Application.create({
        userId: req.user.id,
        masterResumeId,
        companyName: companyName.trim(),
        jobTitle: jobTitle.trim(),
        referenceUrl: (referenceUrl || '').trim(),
        jdSnapshot: jdText,
        jdTextHash,
        coverLetterRequested: Boolean(coverLetterRequested),
        status: 'in_progress',
        // A resume that predates `timestamps: true` has no updatedAt of its
        // own yet on this first read — uploadedAt is the honest fallback.
        masterResumeSnapshotAt: resume.updatedAt || resume.uploadedAt,
      });
    } catch (err) {
      if (err.code === 11000) {
        const winner = await Application.findOne({ masterResumeId, jdTextHash, userId: req.user.id });
        return res.json({ application: winner, deduped: true });
      }
      throw err;
    }

    const applicationId = application._id.toString();
    const graph = getJobAgentGraph();

    // Everything from here on can throw mid-flight (an LLM provider rate
    // limit or outage, a graph error) after the application row above already
    // exists. Without this guard a thrown error left that row stranded at
    // status 'in_progress' forever — invisible in the UI, no error recorded,
    // no way to retry. On any failure past this point, undo the create
    // instead of leaving a row nothing can ever resolve.
    try {
      await graph.invoke(
        {
          applicationId,
          userId: req.user.id,
          masterResumeId,
          companyName: companyName.trim(),
          jdText,
          jdTitle: jobTitle.trim(),
          resumeSummary: resume.summary,
          resumeTitle: resume.personalInfo?.title,
          resumeCanonicalSkills,
          resumeBullets: resumeBulletsForGraph,
          projectCanonicalSkills,
          // Frozen, display-only snapshots — see jobAgentGraph.js.
          resumeProjects: resume.projects || [],
          resumeEducation: resume.education || [],
          resumeCertifications: resume.certifications || [],
          resumeVolunteerWork: resume.volunteerWork || [],
          coverLetterRequested: Boolean(coverLetterRequested),
        },
        { configurable: { thread_id: applicationId }, recursionLimit: GRAPH_RECURSION_LIMIT }
      );

      const snapshot = await graph.getState({ configurable: { thread_id: applicationId } });
      const state = snapshot.values;

      application.jdKeywords = state.jdKeywords;
      application.jdCanonicalSkills = state.jdCanonicalSkills;
      application.keywordGaps = state.keywordGaps;

      if (state.roleFit?.fit === 'low') {
        application.status = 'role_mismatch';
      } else {
        application.status = 'pending_approval';
        application.tailoredBullets = state.tailoredBullets;
        application.tailoredSummary = state.tailoredSummary;
        application.tailoredTitle = state.tailoredTitle;
        application.coverLetterText = state.coverLetterText;
        application.atsScore = state.atsScore;
        application.atsFlags = state.atsFlags;
        application.recruiterFeedback = state.recruiterFeedback;
        application.retryCount = state.retryCount ?? 0;
      }

      await application.save();
    } catch (err) {
      await Application.deleteOne({ _id: applicationId });
      const checkpointer = getCheckpointer();
      await checkpointer.deleteThread(applicationId);
      await GenerationCache.deleteMany({ applicationId });
      throw err;
    }

    return res.status(201).json({ application });
  } catch (err) {
    console.error(err);
    return res.status(500).json({ error: 'Failed to create and start application.' });
  }
});

// For the Approval page — merges the Mongo doc with data section 8 doesn't
// persist (the original bullets, the verification result, the role-mismatch
// reason), sourced live from the checkpointer instead of duplicating it.
router.get('/:id', async (req, res) => {
  const { id } = req.params;
  if (!mongoose.isValidObjectId(id)) {
    return res.status(400).json({ error: 'Invalid application id.' });
  }

  try {
    const application = await Application.findOne({ _id: id, userId: req.user.id });
    if (!application) {
      return res.status(404).json({ error: 'Application not found.' });
    }

    const graph = getJobAgentGraph();
    const snapshot = await graph.getState({ configurable: { thread_id: id } });
    const state = snapshot.values || {};

    const resume = await MasterResume.findOne({ _id: application.masterResumeId, userId: req.user.id }).select(
      'skills projects education certifications volunteerWork updatedAt'
    );

    // Frozen-at-creation snapshot, falling back to a live read only for an
    // application from before these fields existed (state.x is undefined
    // there, never merely empty) — see jobAgentGraph.js.
    const originalProjects = state.resumeProjects ?? resume?.projects ?? [];
    const originalEducation = state.resumeEducation ?? resume?.education ?? [];
    const originalCertifications = state.resumeCertifications ?? resume?.certifications ?? [];
    const originalVolunteerWork = state.resumeVolunteerWork ?? resume?.volunteerWork ?? [];

    // Verified-skills is display-only (see verifiedSkills.js) — scoped to what
    // this specific application will actually export: non-rejected tailored
    // bullets' current text, plus the (frozen) Projects section, which
    // the export always includes verbatim regardless of JD (see exportResumeDocx.js).
    const activeTexts = (application.tailoredBullets || [])
      .filter((bullet) => !bullet.rejected)
      .map((bullet) => bullet.finalText);
    const effectiveSkills = application.tailoredSkills ?? resume?.skills ?? [];
    const sourceTexts = [
      ...activeTexts,
      application.tailoredSummary?.finalText,
      ...originalProjects.map((project) => project.description),
    ];
    const { aliases: idSkillAliases, matchers: idSkillMatchers } = await getSkillDictionaryForUser(req.user.id);
    const { verifiedSkills, skillMatchTypes } = computeVerifiedSkills(effectiveSkills, sourceTexts, idSkillMatchers, idSkillAliases);
    const titleSeniorityWarning = computeTitleSeniorityWarning(application.tailoredTitle);

    // Deliberately false whenever masterResumeSnapshotAt itself is missing
    // (every application created before this field existed) — otherwise
    // every pre-existing application would show "changed" as noise, not
    // signal, the first time this ships.
    const masterResumeChanged = Boolean(
      application.masterResumeSnapshotAt &&
        resume?.updatedAt &&
        resume.updatedAt > application.masterResumeSnapshotAt
    );

    return res.json({
      application,
      originalBullets: state.resumeBullets || [],
      originalSummary: state.resumeSummary || '',
      originalProjects,
      originalEducation,
      originalCertifications,
      originalVolunteerWork,
      masterResumeChanged,
      verificationResult: state.verificationResult || null,
      roleFitReason: application.status === 'role_mismatch' ? state.roleFit?.reason : undefined,
      verifiedSkills,
      skillMatchTypes,
      titleSeniorityWarning,
    });
  } catch (err) {
    console.error(err);
    return res.status(500).json({ error: 'Failed to load application.' });
  }
});

// Single-application delete (distinct from resumes.js's whole-resume cascade
// in section 2.4) — see workflow doc section 2.5. Deletes the application
// document, its checkpoint/thread, and its GenerationCache entries. Not
// gated by status; the only UI entry point (Applications.jsx) happens to
// only ever show approved rows, but this route itself is general.
router.delete('/:id', async (req, res) => {
  const { id } = req.params;
  if (!mongoose.isValidObjectId(id)) {
    return res.status(400).json({ error: 'Invalid application id.' });
  }

  try {
    const application = await Application.findOne({ _id: id, userId: req.user.id });
    if (!application) {
      return res.status(404).json({ error: 'Application not found.' });
    }

    await Application.deleteOne({ _id: id });
    const checkpointer = getCheckpointer();
    await checkpointer.deleteThread(id);
    await GenerationCache.deleteMany({ applicationId: id });

    return res.json({ deleted: true });
  } catch (err) {
    console.error(err);
    return res.status(500).json({ error: 'Failed to delete application.' });
  }
});

// On-demand exports (replaces node 11's automatic tracker.xlsx/docx side
// effects) — generated fresh from Mongo each time, never stored as files.
// Nothing here is exportable until approved, per the "nothing is used
// before I approve it" principle enforced elsewhere in this app.
router.get('/:id/export/resume.docx', async (req, res) => {
  const { id } = req.params;
  if (!mongoose.isValidObjectId(id)) {
    return res.status(400).json({ error: 'Invalid application id.' });
  }

  try {
    const application = await Application.findOne({ _id: id, userId: req.user.id });
    if (!application) {
      return res.status(404).json({ error: 'Application not found.' });
    }
    if (application.status !== 'approved') {
      return res.status(400).json({ error: 'This application has not been approved yet.' });
    }

    const resume = await MasterResume.findOne({ _id: application.masterResumeId, userId: req.user.id });
    const graph = getJobAgentGraph();
    const snapshot = await graph.getState({ configurable: { thread_id: id } });
    const originalBullets = snapshot.values?.resumeBullets || [];
    const originalBulletsById = new Map(originalBullets.map((bullet) => [bullet.bulletId, bullet]));

    const buffer = await buildResumeDocxBuffer({
      personalInfo: resume?.personalInfo || {},
      tailoredSummary: application.tailoredSummary,
      tailoredTitle: application.tailoredTitle,
      tailoredBullets: application.tailoredBullets.filter((bullet) => !bullet.rejected),
      originalBulletsById,
      // Frozen-at-creation snapshot, falling back to a live read only for an
      // application from before these fields existed — see jobAgentGraph.js.
      education: snapshot.values?.resumeEducation ?? resume?.education ?? [],
      projects: snapshot.values?.resumeProjects ?? resume?.projects ?? [],
      certifications: snapshot.values?.resumeCertifications ?? resume?.certifications ?? [],
      volunteerWork: snapshot.values?.resumeVolunteerWork ?? resume?.volunteerWork ?? [],
      skills: application.tailoredSkills ?? resume?.skills ?? [],
    });

    const filename = buildExportFilename({
      fullName: resume?.personalInfo?.fullName,
      companyName: application.companyName,
      suffix: 'Resume',
    });
    res.set({
      'Content-Type': 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
      'Content-Disposition': `attachment; filename="${filename}"`,
    });
    return res.send(buffer);
  } catch (err) {
    console.error(err);
    return res.status(500).json({ error: 'Failed to generate resume.' });
  }
});

