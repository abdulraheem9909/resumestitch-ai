// The endpoint that actually resumes the paused graph. action: 'approve'
// merges the current (possibly hand-edited) content and ends the run;
// action: 'retry' sends it back through tailorContent -> deterministicVerification
// -> (coverLetterGeneration) -> styleLinting -> atsScoreAndRecruiter -> humanApproval
// with the given notes, pausing again (possibly after further automatic
// retries within that same pass, capped at 3 — see shouldRetryAutomatically).
// action: 'override' is only valid on a role_mismatch application — the human
// disagrees with node 4's gate and sends it straight to tailorContent,
// bypassing the gate entirely rather than re-running it (which would very
// likely reproduce the same verdict). This is the one place in the pipeline
// that previously had no recourse once the gate fired — every other decision
// point already lets the human have the final say.
router.post('/:id/resume', async (req, res) => {
  const { id } = req.params;
  if (!mongoose.isValidObjectId(id)) {
    return res.status(400).json({ error: 'Invalid application id.' });
  }

  const { action, notes } = req.body;
  if (action !== 'approve' && action !== 'retry' && action !== 'override') {
    return res.status(400).json({ error: "action must be 'approve', 'retry', or 'override'." });
  }
  if (action === 'retry' && (typeof notes !== 'string' || !notes.trim())) {
    return res.status(400).json({ error: 'notes is required for a retry.' });
  }

  try {
    const application = await Application.findOne({ _id: id, userId: req.user.id });
    if (!application) {
      return res.status(404).json({ error: 'Application not found.' });
    }
    if (action === 'override') {
      if (application.status !== 'role_mismatch') {
        return res.status(400).json({ error: 'override is only valid for a role-mismatch application.' });
      }
    } else {
      if (application.status === 'role_mismatch') {
        return res.status(400).json({ error: 'This application was a role mismatch — there is nothing to approve or retry.' });
      }
      if (application.status === 'approved') {
        return res.status(400).json({ error: 'This application has already been approved.' });
      }
      if (action === 'retry' && (application.retryCount ?? 0) >= MAX_RETRY_COUNT) {
        return res.status(400).json({ error: `This application has already used all ${MAX_RETRY_COUNT} retries.` });
      }
    }

    const resumePayload =
      action === 'approve'
        ? {
            action: 'approve',
            tailoredBullets: application.tailoredBullets,
            tailoredSummary: application.tailoredSummary,
            tailoredTitle: application.tailoredTitle,
          }
        : action === 'retry'
          ? {
              action: 'retry',
              notes,
              tailoredBullets: application.tailoredBullets,
              tailoredSummary: application.tailoredSummary,
              tailoredTitle: application.tailoredTitle,
            }
          : { action: 'override' };

    const snapshot = await resumeGraph(id, resumePayload);
    const state = snapshot.values;

    if (action === 'approve') {
      application.status = 'approved';
      application.approvedAt = new Date();
      application.tailoredBullets = state.tailoredBullets;
      application.tailoredSummary = state.tailoredSummary;
      application.tailoredTitle = state.tailoredTitle;
      application.coverLetterText = state.coverLetterText;
      application.atsScore = state.atsScore;
      application.atsFlags = state.atsFlags;
      application.recruiterFeedback = state.recruiterFeedback;
      application.retryCount = state.retryCount ?? application.retryCount;
    } else if (action === 'retry') {
      application.status = 'pending_approval';
      application.retryNotes.push({ notes });
      application.tailoredBullets = state.tailoredBullets;
      application.tailoredSummary = state.tailoredSummary;
      application.tailoredTitle = state.tailoredTitle;
      application.keywordGaps = state.keywordGaps;
      application.coverLetterText = state.coverLetterText;
      application.atsScore = state.atsScore;
      application.atsFlags = state.atsFlags;
      application.recruiterFeedback = state.recruiterFeedback;
      application.retryCount = state.retryCount;

      // Refresh the human-recheck panel against this round's fresh content —
      // otherwise it keeps showing whatever it said before this retry, which
      // reads as "nothing changed" even though the tailored content did.
      const recheckResult = await computeHumanRecheck(application);
      Object.assign(application, recheckResult);
    } else {
      // override — first time this application ever runs tailorContent, so
      // this mirrors POST /'s own "plausible" branch, not the retry branch.
      application.status = 'pending_approval';
      application.retryNotes.push({ notes: 'Role-fit gate manually overridden by user — proceeded to tailoring.' });
      application.tailoredBullets = state.tailoredBullets;
      application.tailoredSummary = state.tailoredSummary;
      application.tailoredTitle = state.tailoredTitle;
      application.keywordGaps = state.keywordGaps;
      application.coverLetterText = state.coverLetterText;
      application.atsScore = state.atsScore;
      application.atsFlags = state.atsFlags;
      application.recruiterFeedback = state.recruiterFeedback;
      application.retryCount = state.retryCount ?? 0;

      const recheckResult = await computeHumanRecheck(application);
      Object.assign(application, recheckResult);
    }

    await application.save();

    return res.json({ application });
  } catch (err) {
    console.error(err);
    return res.status(500).json({ error: 'Failed to resume application.' });
  }
});

// Section 4a — suggest missing skills. Never inserts text directly into the
// tailored output: goes through the same tagBullet flow as a normal upload,
// then retries with it in the pool. saveToMasterResume (default true) decides
// where it lives:
//   true  — a real resumeBullets document, same as today: permanent, shared
//           with every other application against this master resume.
//   false — scoped to just this application. Never written to resumeBullets
//           at all, so no other application, gap-analysis run, or the Master
//           Resume bullets page ever sees it — it only exists inside this
//           application's own graph state, and disappears automatically
//           if/when this application is deleted (its checkpoint thread is
//           deleted too, and that's the only place this bullet ever lived).
router.post('/:id/suggest-skills/accept', async (req, res) => {
  const { id } = req.params;
  if (!mongoose.isValidObjectId(id)) {
    return res.status(400).json({ error: 'Invalid application id.' });
  }

  const { skill, bulletText, role, company, dateRange, saveToMasterResume = true } = req.body;
  if (typeof skill !== 'string' || !skill.trim()) {
    return res.status(400).json({ error: 'skill is required.' });
  }
  if (typeof bulletText !== 'string' || !bulletText.trim()) {
    return res.status(400).json({ error: 'bulletText is required.' });
  }
  if (typeof saveToMasterResume !== 'boolean') {
    return res.status(400).json({ error: 'saveToMasterResume must be a boolean.' });
  }

  try {
    const application = await Application.findOne({ _id: id, userId: req.user.id });
    if (!application) {
      return res.status(404).json({ error: 'Application not found.' });
    }
    if (application.status === 'role_mismatch' || application.status === 'approved') {
      return res.status(400).json({ error: 'Cannot suggest a skill for this application.' });
    }
    if ((application.retryCount ?? 0) >= MAX_RETRY_COUNT) {
      return res.status(400).json({ error: `This application has already used all ${MAX_RETRY_COUNT} retries.` });
    }
    if (!(application.keywordGaps || []).includes(skill)) {
      return res.status(400).json({ error: "skill is not one of this application's keyword gaps." });
    }

    const { skills, metrics } = await tagBullet(bulletText);
    const { aliases: suggestSkillAliases } = await getSkillDictionaryForUser(req.user.id);
    const canonicalSkills = skills.map((s) => canonicalizeSkill(s, suggestSkillAliases));
    const trimmedRole = typeof role === 'string' && role.trim() ? role.trim() : undefined;
    const trimmedCompany = typeof company === 'string' && company.trim() ? company.trim() : undefined;
    const trimmedDateRange = typeof dateRange === 'string' && dateRange.trim() ? dateRange.trim() : undefined;

    const masterBullets = await ResumeBullet.find({ masterResumeId: application.masterResumeId }).sort({ order: 1 });

    let newBullet;
    let resumeBulletsForGraph;
    let requiredBulletId;

    if (saveToMasterResume) {
      // Appends after everything already on the master resume — see the
      // `order` field's own comment on ResumeBullet.js.
      const nextOrder = (masterBullets[masterBullets.length - 1]?.order ?? -1) + 1;
      newBullet = await ResumeBullet.create({
        masterResumeId: application.masterResumeId,
        text: bulletText,
        order: nextOrder,
        skills,
        canonicalSkills,
        metrics,
        role: trimmedRole,
        company: trimmedCompany,
        dateRange: trimmedDateRange,
      });
      resumeBulletsForGraph = buildResumeBulletsForGraph([...masterBullets, newBullet]);
      requiredBulletId = newBullet._id.toString();
    } else {
      // A bullet privately added earlier in THIS application lives only in
      // this thread's own state, never in resumeBullets — so a fresh Mongo
      // read alone would silently drop it. Carry forward anything already in
      // the current candidate pool that isn't one of the real master bullets.
      const masterBulletIds = new Set(masterBullets.map((bullet) => bullet._id.toString()));
      const graph = getJobAgentGraph();
      const currentSnapshot = await graph.getState({ configurable: { thread_id: id } });
      const existingPrivateBullets = (currentSnapshot.values?.resumeBullets || []).filter(
        (bullet) => !masterBulletIds.has(bullet.bulletId)
      );

      newBullet = {
        bulletId: randomUUID(),
        text: bulletText,
        skills,
        canonicalSkills,
        metrics,
        role: trimmedRole,
        company: trimmedCompany,
        dateRange: trimmedDateRange,
      };
      resumeBulletsForGraph = [
        ...buildResumeBulletsForGraph(masterBullets),
        ...existingPrivateBullets,
        {
          bulletId: newBullet.bulletId,
          text: newBullet.text,
          role: newBullet.role,
          company: newBullet.company,
          dateRange: newBullet.dateRange,
          canonicalSkills: newBullet.canonicalSkills,
        },
      ];
      requiredBulletId = newBullet.bulletId;
    }

    const notes =
      `New skill added to resume: "${skill}". New bullet: "${bulletText}". ` +
      'Consider incorporating this bullet into the tailored content if relevant.';

    const snapshot = await resumeGraph(id, {
      action: 'retry',
      notes,
      tailoredBullets: application.tailoredBullets,
      tailoredSummary: application.tailoredSummary,
      tailoredTitle: application.tailoredTitle,
      resumeBullets: resumeBulletsForGraph,
      requiredBulletId,
    });
    const state = snapshot.values;

    application.status = 'pending_approval';
    application.retryNotes.push({ notes });
    application.tailoredBullets = state.tailoredBullets;
    application.tailoredSummary = state.tailoredSummary;
    application.tailoredTitle = state.tailoredTitle;
    application.keywordGaps = state.keywordGaps;
    application.coverLetterText = state.coverLetterText;
    application.atsScore = state.atsScore;
    application.atsFlags = state.atsFlags;
    application.recruiterFeedback = state.recruiterFeedback;
    application.retryCount = state.retryCount;
    await application.save();

    return res.json({ application, newBullet, scope: saveToMasterResume ? 'master' : 'application' });
  } catch (err) {
    console.error(err);
    return res.status(500).json({ error: 'Failed to add suggested skill.' });
  }
});

