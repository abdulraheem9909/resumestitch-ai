// LangGraph's default recursionLimit is 25 super-steps. A single pass that
// legitimately uses all 3 automatic retries (section 5) costs 9 + 3×6 = 27
// steps with a cover letter requested (coverLetterGeneration adds one node
// per cycle), or 8 + 3×5 = 23 without one — so the documented, correctly-
// enforced retry cap could still blow past the default limit and crash with
// an uncaught GraphRecursionError before ever reaching node 10. Raised with
// headroom rather than tuned to the exact worst case, since a manual retry
// or an accepted skill suggestion (also routed through this same invoke)
// can itself trigger further automatic retries on top.
const GRAPH_RECURSION_LIMIT = 60;

// Section 5 — "Cap retries at 3 regardless of reason," shared across
// automatic retries (enforced inside shouldRetryAutomatically) and manual
// ones. A manual "send back with notes" or an accepted suggest-missing-
// skills bullet both route through the same POST-triggered retry pathway
// (section 4a) but never went through the automatic loop's own cap check,
// so retryCount could otherwise climb past 3 indefinitely — checked here,
// before either route ever invokes the graph, so a refused retry costs
// nothing (no LLM call, no DB write).
const MAX_RETRY_COUNT = 3;

function buildResumeBulletsForGraph(bullets) {
  return bullets.map((bullet) => ({
    bulletId: bullet._id.toString(),
    text: bullet.text,
    role: bullet.role,
    company: bullet.company,
    dateRange: bullet.dateRange,
    canonicalSkills: bullet.canonicalSkills,
  }));
}

// A short, human-recognizable stand-in for a bullet in a flag message — never
// its internal id, which means nothing to whoever's reading the flag.
function truncateForFlag(text, maxLength = 50) {
  if (!text) return '';
  return text.length > maxLength ? `${text.slice(0, maxLength).trimEnd()}…` : text;
}

// Display-only, never persisted — same "compute live, don't store" pattern
// as verifiedSkills/skillMatchTypes. Only meaningful for a hand-edited title,
// since the AI suggestion can never contain one of these words by construction.
function computeTitleSeniorityWarning(tailoredTitle) {
  if (tailoredTitle?.editSource !== 'human') return [];
  return findUnsupportedSeniorityTerms(tailoredTitle.finalText);
}

// Resumes the one interrupt() in node 10 with a Command, then reads back the
// resulting checkpoint — the only place this route file touches the graph.
async function resumeGraph(applicationId, resumePayload) {
  const graph = getJobAgentGraph();
  await graph.invoke(new Command({ resume: resumePayload }), {
    configurable: { thread_id: applicationId },
    recursionLimit: GRAPH_RECURSION_LIMIT,
  });
  return graph.getState({ configurable: { thread_id: applicationId } });
}

// Section 4a — re-check computation. Runs node 6 AND node 9 against an
// application's CURRENT tailoredBullets/tailoredSummary (possibly hand-edited,
// or freshly regenerated by a retry), without saving. Shared by the standalone
// POST /:id/recheck route and by the retry branch of POST /:id/resume, so the
// human-recheck panel reflects a fresh retry immediately instead of only
// updating on the next manual "Re-check edited text" click.
async function computeHumanRecheck(application) {
  const graph = getJobAgentGraph();
  const snapshot = await graph.getState({ configurable: { thread_id: application._id.toString() } });
  const { resumeBullets = [], matchedSkills = [], yearsOfExperience, resumeTitle } = snapshot.values || {};
  const bulletsById = new Map(resumeBullets.map((bullet) => [bullet.bulletId, bullet]));
  const { aliases, matchers } = await getSkillDictionaryForUser(application.userId.toString());

  const bulletResults = application.tailoredBullets.map((tailoredBullet) => {
    const sourceBullet = bulletsById.get(tailoredBullet.sourceBulletId);
    const result =
      tailoredBullet.editSource === 'human'
        ? trustHumanEdit(tailoredBullet.finalText, matchers, aliases)
        : verifyBullet({ generatedText: tailoredBullet.finalText, sourceBullet }, matchers, aliases);
    return { bulletId: tailoredBullet.bulletId, rejected: tailoredBullet.rejected, finalText: tailoredBullet.finalText, ...result };
  });
  const bulletFlags = bulletResults.flatMap((result) => {
    const label = truncateForFlag(result.finalText);
    return [
      ...result.fabricatedSkills.map((skill) => `Bullet "${label}": fabricated skill "${skill}"`),
      ...result.fabricatedMetrics.map((metric) => `Bullet "${label}": fabricated metric "${metric}"`),
    ];
  });

  const selectedBullets = application.tailoredBullets
    .filter((tailoredBullet) => !tailoredBullet.rejected)
    .map((tailoredBullet) => bulletsById.get(tailoredBullet.sourceBulletId));
  const summaryResult = !application.tailoredSummary
    ? { passed: true, fabricatedSkills: [], fabricatedMetrics: [], claimedSkills: [] }
    : application.tailoredSummary.editSource === 'human'
      ? trustHumanEdit(application.tailoredSummary.finalText, matchers, aliases)
      : verifySummary(
          {
            generatedText: application.tailoredSummary.finalText,
            matchedSkills,
            selectedBullets,
            yearsOfExperience,
          },
          matchers,
          aliases
        );

  const summaryFlags = [
    ...summaryResult.fabricatedSkills.map((skill) => `Summary: fabricated skill "${skill}"`),
    ...summaryResult.fabricatedMetrics.map((metric) => `Summary: fabricated metric "${metric}"`),
  ];

  const overallPassed = bulletResults.every((result) => result.passed) && summaryResult.passed;

  // A live view of what's actually missing from the file you're about to
  // download — deliberately NOT unioned with the master resume's permanent
  // skill tags. Those tags describe your resume as a whole, not this specific
  // tailored output; a skill can be permanently tagged on some other bullet
  // while being completely absent from every bullet that's actually part of
  // this application (rejected, or edited to remove it) — in that case the
  // exported file genuinely doesn't cover it, and this list must say so.
  // Never overwrites the original keywordGaps, which stays tied to the master
  // resume for the separate "worth adding a permanent bullet" decision.
  const verifiedBulletSkills = bulletResults
    .filter((result) => !result.rejected)
    .flatMap((result) => result.claimedSkills.filter((skill) => !result.fabricatedSkills.includes(skill)));
  const verifiedSummarySkills = summaryResult.claimedSkills.filter((skill) => !summaryResult.fabricatedSkills.includes(skill));
  const effectiveSkills = [...new Set([...verifiedBulletSkills, ...verifiedSummarySkills])];
  const humanRecheckKeywordGaps = gapAnalysis(application.jdCanonicalSkills, effectiveSkills);

  const atsResult = await atsScoreAndRecruiter({
    jdText: application.jdSnapshot,
    tailoredBullets: application.tailoredBullets.filter((bullet) => !bullet.rejected),
    tailoredSummary: application.tailoredSummary,
    resumeTitle: application.tailoredTitle?.finalText || resumeTitle,
    coverLetterText: application.coverLetterText,
    keywordGaps: humanRecheckKeywordGaps,
    verificationResult: { bullets: bulletResults, summary: summaryResult, overallPassed },
    applicationId: application._id.toString(),
    resumeVersion: application.masterResumeId,
  });

  return {
    humanRecheckAtsScore: atsResult.atsScore,
    // No prefix on these — same bare enum values (e.g. "missingRequirement") as
    // the original AI pass's atsFlags, so the two never look like different
    // kinds of thing when the UI swaps between them in the same slot.
    humanRecheckAtsFlags: [...bulletFlags, ...summaryFlags, ...atsResult.atsFlags],
    humanRecheckRecruiterFeedback: atsResult.recruiterFeedback,
    humanRecheckKeywordGaps,
  };
}

